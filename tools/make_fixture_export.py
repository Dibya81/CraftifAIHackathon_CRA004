"""SiteSentinel Fixture Export Generator.

Builds a clearly labelled fake PipeGen export folder in a temporary directory
to exercise scripts/ingest_pipegen_export.sh end-to-end without real hardware or GPU.

The generated folder contains:
- FIXTURE_EXPORT_DO_NOT_SUBMIT marker file
- run.sh stub
- config.json stub
- sample_detection.json
- NO .engine or .plan files (unless --with-engine is explicitly given for testing)
"""

from __future__ import annotations

import argparse
import json
import stat
import tempfile
from pathlib import Path

FIXTURE_MARKER_CONTENT = """================================================================================
FIXTURE EXPORT - DO NOT SUBMIT OR PROMOTE
================================================================================
This directory is a synthetic rehearsal fixture generated by
tools/make_fixture_export.py.

It contains NO valid TensorRT engine binaries, NO compiled GPU pipelines,
and NO real PipeGen compilation outputs.

Ingesting this directory into production pipegen/export/ is strictly forbidden
and blocked by scripts/ingest_pipegen_export.sh and evidence/ledger.yaml guards.
================================================================================
"""

STUB_RUN_SH = """#!/usr/bin/env bash
echo "SiteSentinel Fixture Runner Stub (DO NOT RUN ON HARDWARE)"
exit 1
"""

STUB_CONFIG_JSON = {
    "project": "SiteSentinel",
    "pipegen_version": "fixture-stub-v0.0.0",
    "pipeline_name": "worker_safety_pipeline",
    "mode": "FIXTURE",
    "streams": 1,
    "batch_size": 1,
    "input_resolution": [1920, 1080],
    "models": [
        {
            "name": "yolov8_ppe",
            "type": "detection",
            "classes": ["person", "helmet", "vest"],
            "engine_path": "model.engine.stub",
        }
    ],
}

STUB_SAMPLE_DETECTION = {
    "camera_id": "cam-01",
    "frame_id": 1,
    "ts": 1776435600.0,
    "frame": {"width": 1920, "height": 1080},
    "objects": [
        {
            "track_id": 101,
            "class": "person",
            "conf": 0.95,
            "bbox": [500.0, 300.0, 700.0, 800.0],
        },
        {
            "track_id": None,
            "class": "helmet",
            "conf": 0.92,
            "bbox": [540.0, 310.0, 660.0, 410.0],
        },
    ],
}


def build_fixture_export(
    target_dir: Path | str,
    with_engine: bool = False,
    with_marker: bool = True,
) -> Path:
    out_path = Path(target_dir).resolve()
    out_path.mkdir(parents=True, exist_ok=True)

    # 1. Marker file
    if with_marker:
        marker_file = out_path / "FIXTURE_EXPORT_DO_NOT_SUBMIT"
        marker_file.write_text(FIXTURE_MARKER_CONTENT, encoding="utf-8")

    # 2. run.sh stub
    run_file = out_path / "run.sh"
    run_file.write_text(STUB_RUN_SH, encoding="utf-8")
    run_file.chmod(run_file.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

    # 3. config.json stub
    cfg_file = out_path / "config.json"
    cfg_file.write_text(json.dumps(STUB_CONFIG_JSON, indent=2), encoding="utf-8")

    # 4. sample_detection.json
    det_file = out_path / "sample_detection.json"
    det_file.write_text(json.dumps(STUB_SAMPLE_DETECTION, indent=2), encoding="utf-8")

    # 5. Optional engine stub for testing target verification
    if with_engine:
        engine_file = out_path / "model.engine"
        engine_file.write_text("MOCK_TENSORRT_ENGINE_BYTES_FOR_REHEARSAL_ONLY", encoding="utf-8")

    return out_path


def main() -> None:
    parser = argparse.ArgumentParser(description="Create a synthetic PipeGen export fixture.")
    parser.add_argument(
        "--output-dir",
        "-o",
        type=str,
        default=None,
        help="Target directory. If not specified, a temporary directory is created.",
    )
    parser.add_argument(
        "--with-engine",
        action="store_true",
        help="Include a stub .engine file (for unit testing ingestion scripts only).",
    )
    parser.add_argument(
        "--no-marker",
        action="store_true",
        help="Omit FIXTURE_EXPORT_DO_NOT_SUBMIT marker (for negative unit tests).",
    )

    args = parser.parse_args()

    if args.output_dir:
        out_dir = Path(args.output_dir)
    else:
        out_dir = Path(tempfile.mkdtemp(prefix="pipegen_fixture_export_"))

    created = build_fixture_export(
        target_dir=out_dir,
        with_engine=args.with_engine,
        with_marker=not args.no_marker,
    )

    print(f"Fixture export created at: {created}")
    for item in sorted(created.iterdir()):
        print(f"  - {item.name} ({item.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
